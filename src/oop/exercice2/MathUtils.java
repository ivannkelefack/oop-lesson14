package oop.exercice2;

public class MathUtils {

    // Two integers
    public int sum(int a, int b){
        return a+ b;
    }

    // Two double
    public double sum(double a, double b){
        return a+ b;
    }

    // Two String - concatenation
    public String sum(String a, String b){
        return a+ b;
    }

    // Three integers
    public int sum(int a, int b, int c){
        return a+ b;
    }


}
